using System.Text;
using System.Text.Json;
using WorkspaceOrganizer.Core.Models;

namespace WorkspaceOrganizer.Core.Profiles;

/// <summary>What <c>wso</c> and the shims read: everything needed to run a program in the profile.</summary>
/// <param name="BrowserId">The workspace's browser (a <c>BrowserCatalog</c> id), used by <c>wso open</c>.</param>
/// <param name="BrowserProfile">An existing browser profile name, or null for the isolated data dir.</param>
public sealed record ProfileMarker(
    string Id,
    string Name,
    string Folder,
    Dictionary<string, string> Variables,
    List<string> PathPrefix,
    string? BrowserId = null,
    string? BrowserProfile = null)
{
    static readonly JsonSerializerOptions Options = new() { WriteIndented = true, PropertyNamingPolicy = JsonNamingPolicy.CamelCase };

    public ProfileEnvironment Environment => new(Variables, PathPrefix);

    public string ToJson() => JsonSerializer.Serialize(this, Options);

    public static ProfileMarker? TryRead(string path)
    {
        try
        {
            return File.Exists(path) ? JsonSerializer.Deserialize<ProfileMarker>(File.ReadAllText(path), Options) : null;
        }
        catch (Exception ex) when (ex is JsonException or IOException or UnauthorizedAccessException)
        {
            return null;
        }
    }
}

/// <summary>Materializes profile folders on disk from the organizer's data.</summary>
public static class ProfileWriter
{
    public static void WriteAll(OrganizerData data)
    {
        var root = data.Settings.ProfilesRoot;
        var current = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var workspace in data.Workspaces)
        {
            var layout = new ProfileLayout(root, workspace.Folder);
            Write(workspace, layout);
            current.Add(layout.Folder);
        }
        RetireRemoved(root, current);
    }

    public static void Write(Workspace workspace, ProfileLayout layout)
    {
        Directory.CreateDirectory(layout.Bin);
        if (workspace.RedirectHome)
        {
            Directory.CreateDirectory(Path.Combine(layout.Home, "AppData", "Roaming"));
            Directory.CreateDirectory(Path.Combine(layout.Home, "AppData", "Local"));
        }
        foreach (var tool in CliToolCatalog.Enabled(workspace.EnabledTools))
        {
            Directory.CreateDirectory(layout.Config(tool.Id));
            tool.Seed?.Invoke(layout);
        }

        var environment = ProfileEnvironment.Build(workspace, layout);
        var marker = new ProfileMarker(workspace.Id, workspace.Name, layout.Folder,
            new Dictionary<string, string>(environment.Variables), [.. environment.PathPrefix],
            workspace.BrowserId, string.IsNullOrWhiteSpace(workspace.BrowserProfile) ? null : workspace.BrowserProfile.Trim());
        WriteIfChanged(layout.Marker, marker.ToJson());
        WriteIfChanged(layout.ActivatePowerShell, PowerShellScript(layout.Folder, workspace.Name, environment));
        WriteIfChanged(layout.ActivateCmd, CmdScript(layout.Folder, workspace.Name, environment));
    }

    /// <summary>
    /// A removed workspace keeps its files, but loses its marker and activate scripts so shims and
    /// <c>wso</c> stop treating the folder as a profile.
    /// </summary>
    static void RetireRemoved(string root, HashSet<string> current)
    {
        if (!Directory.Exists(root))
            return;
        foreach (var directory in Directory.EnumerateDirectories(root))
        {
            var layout = new ProfileLayout(root, Path.GetFileName(directory));
            if (current.Contains(layout.Folder) || !File.Exists(layout.Marker))
                continue;
            File.Delete(layout.Marker);
            File.Delete(layout.ActivatePowerShell);
            File.Delete(layout.ActivateCmd);
        }
    }

    public static string PowerShellScript(string folder, string name, ProfileEnvironment environment)
    {
        static string Quote(string value) => "'" + value.Replace("'", "''") + "'";

        var script = new StringBuilder()
            .AppendLine($"# Generated by Workspace Organizer for the \"{name}\" profile. Changes are overwritten.")
            .AppendLine("# Use it with:  . .\\activate.ps1");
        foreach (var (key, value) in environment.Variables.OrderBy(kv => kv.Key, StringComparer.Ordinal))
            script.AppendLine($"Set-Item -Path {Quote("env:" + key)} -Value {Quote(value)}");
        var separator = Quote(Path.PathSeparator.ToString());
        foreach (var prefix in environment.PathPrefix.Reverse())
            script.AppendLine($"$env:PATH = {Quote(prefix + Path.PathSeparator)} + ((($env:PATH -split {separator}) -ne {Quote(prefix)}) -join {separator})");
        script
            .AppendLine("if (-not (Test-Path function:global:__wso_original_prompt)) { Copy-Item function:prompt function:global:__wso_original_prompt }")
            .AppendLine($"function global:prompt {{ {Quote($"[{folder}] ")} + (__wso_original_prompt) }}");
        return script.ToString();
    }

    public static string CmdScript(string folder, string name, ProfileEnvironment environment)
    {
        static string Escape(string value) => value.Replace("%", "%%");

        var script = new StringBuilder()
            .AppendLine("@echo off")
            .AppendLine($"rem Generated by Workspace Organizer for the \"{name}\" profile. Changes are overwritten.");
        foreach (var (key, value) in environment.Variables.OrderBy(kv => kv.Key, StringComparer.Ordinal))
            script.AppendLine($"set \"{key}={Escape(value)}\"");
        foreach (var prefix in environment.PathPrefix.Reverse())
            script.AppendLine($"set \"PATH={Escape(prefix)};%PATH%\"");
        script.AppendLine($"prompt [{folder}] $P$G");
        return script.ToString();
    }

    static void WriteIfChanged(string path, string content)
    {
        if (!File.Exists(path) || File.ReadAllText(path) != content)
            File.WriteAllText(path, content);
    }
}
